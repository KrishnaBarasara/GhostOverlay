const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
    getAppState: () => ipcRenderer.invoke('get-app-state'),
    onToggleAutoStreamFrontend: (callback) => ipcRenderer.on('toggle-auto-stream-frontend', callback),
    sendStartOverlay: (settings) => ipcRenderer.send('start-overlay', settings),
    onLockToggled: (callback) => ipcRenderer.on('on-lock-toggled', (_event, isLocked) => callback(isLocked)),
    getBounds: () => ipcRenderer.invoke('get-bounds'),
    setBounds: (bounds) => ipcRenderer.send('set-bounds', bounds),
    getDesktopSourceId: () => ipcRenderer.invoke('get-desktop-source-id'),
    sendFrontendLog: (msg) => ipcRenderer.send('frontend-log', msg),
    uiRecordBtnClicked: () => ipcRenderer.send('ui-record-btn-clicked'),
    uiTranslateBtnClicked: () => ipcRenderer.send('ui-translate-btn-clicked'),
    onToggleAudio: (callback) => ipcRenderer.on('toggle-audio', callback),
    sendAudioBuffer: (buffer) => ipcRenderer.send('process-audio-buffer', buffer),
    onTranscriptReady: (callback) => ipcRenderer.on('transcript-ready', (_event, text) => callback(text)),
    onTranscribeAudio: (callback) => ipcRenderer.on('transcribe-audio', callback),
    onAiThinkingStart: (callback) => ipcRenderer.on('ai-thinking-start', callback),
    onHighlightQuestion: (callback) => ipcRenderer.on('highlight-question', callback),
    onAiResponseReady: (callback) => ipcRenderer.on('ai-response-ready', (_event, text) => callback(text)),
    onAiResponseError: (callback) => ipcRenderer.on('ai-response-error', (_event, text) => callback(text)),
    setHoverState: (isHovering) => ipcRenderer.send('set-hover-state', isHovering),
    setLockState: (isLocked) => ipcRenderer.send('set-lock-state', isLocked),
    manualToggleLock: () => ipcRenderer.send('manual-toggle-lock'),
    manualKill: () => ipcRenderer.send('manual-kill'),
    startCustomResize: (edge) => ipcRenderer.send('start-custom-resize', edge),
    stopCustomResize: () => ipcRenderer.send('stop-custom-resize'),
    startCustomDrag: () => ipcRenderer.send('start-custom-drag'),
    stopCustomAction: () => ipcRenderer.send('stop-custom-action'),
    changeTheme: (theme) => ipcRenderer.send('change-theme', theme),
    onUpdateTheme: (callback) => ipcRenderer.on('update-theme', (event, theme) => callback(theme)),

    // --- Auto Mode: AssemblyAI Streaming Channels ---
    getDesktopId: () => ipcRenderer.invoke('get-desktop-id'),
    sendAssemblyAudioChunk: (buffer) => ipcRenderer.send('assembly-audio-chunk', buffer),
    onAssemblyPartial: (callback) => ipcRenderer.on('assembly-partial', (event, text) => callback(text)),
    onAssemblyFinal: (callback) => ipcRenderer.on('assembly-final', (event, text) => callback(text)),
    onToggleAutoUI: (callback) => ipcRenderer.on('toggle-auto-ui', (event, isVisible) => callback(isVisible)),
    onStartAutoCapture: (callback) => ipcRenderer.on('start-auto-capture', callback),
    onStopAutoCapture: (callback) => ipcRenderer.on('stop-auto-capture', callback),
    onAssemblyStatus: (callback) => ipcRenderer.on('assembly-status', (event, status) => callback(status)),
    onClearRolling: (callback) => ipcRenderer.on('clear-rolling', callback),
    onAiStreamStart: (callback) => ipcRenderer.on('ai-stream-start', (event, tabType) => callback(tabType)),
    onAiTokenStream: (callback) => ipcRenderer.on('ai-token-stream', (event, data) => callback(data)),
    onAiStreamEnd: (callback) => ipcRenderer.on('ai-stream-end', (event, tabType) => callback(tabType)),
    updatePreferredTab: (tab) => ipcRenderer.send('update-preferred-tab', tab),
    onToggleAutoUi: (callback) => ipcRenderer.on('toggle-auto-ui', (event, isAuto) => callback(isAuto))
});
